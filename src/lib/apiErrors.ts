export function apiError(error: unknown): string {
  const e = error as { message?: string; code?: string; details?: string };
  if (e?.message?.includes("CATALOG_FUTURE_BOOKINGS") && /^\d+$/.test(e.details || ""))
    return `Предстоящих или текущих неотменённых записей: ${e.details}. ${messages.CATALOG_FUTURE_BOOKINGS}`;
  for (const [key, value] of Object.entries(messages))
    if (e?.message?.includes(key)) return value;
  if (e?.code === "23P01") return messages.SLOT_UNAVAILABLE;
  if (e?.code === "42501" || e?.code === "PGRST301" || e?.code === "PGRST302")
    return "Доступ запрещён или сеанс истёк. Войдите снова.";
  if (e?.code?.startsWith("22") || e?.code?.startsWith("23"))
    return "Проверьте заполнение полей: сервер отклонил некорректные данные.";
  return "Не удалось получить подтверждение от сервера. Проверьте соединение и повторите действие: повторный запрос не создаст дубль.";
}
